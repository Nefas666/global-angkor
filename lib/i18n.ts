const normalize = (value: string) => value.replace(/\s+/g, " ").trim()

export const dictionary = new Map(entries.map(([it, en, km]) => [normalize(it), { en, km }]))

const prefixes: [string, Record<Exclude<Language, "it">, string>][] = [["Paga ", { en: "Pay ", km: "បង់ " }]]

export function translateString(value: string, language: Language) {
  if (language === "it") return value
  for (const [prefix, target] of prefixes) {
    if (value.startsWith(prefix)) return `${target[language]}${value.slice(prefix.length)}`
  }
  const hit = dictionary.get(normalize(value))
  if (!hit) return value
  const lead = value.match(/^\s*/)?.[0] ?? ""
  const trail = value.match(/\s*$/)?.[0] ?? ""
  return `${lead}${hit[language]}${trail}`
}
